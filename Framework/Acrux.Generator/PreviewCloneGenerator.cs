using System.Collections.Generic;
using System.Linq;
using System.Text;
using Adk.Analyzer;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Acrux.Generator;

/// <summary>
/// Generates the IDE preview's clone of every view model with <c>[PreviewWith]</c> members (and of the view models it
/// reaches): <c>FooViewModelPreview</c>, whose static properties are the preview's design data (the Rider plugin
/// edits them) and whose <c>Default</c> is the clone the views preview with, and <c>FooViewModelPreviewModel</c>, the
/// clone itself: every bindable member of the original as a settable observable property. Output is design code
/// (ADK's <see cref="DesignSources"/>: the design suffix mdk.ini ignores), so MDK does not pack it. What is cloned is decided by <see cref="PreviewClones"/>.
/// </summary>
[Generator]
public sealed class PreviewCloneGenerator : IIncrementalGenerator
{
    static readonly DiagnosticDescriptor InvalidValue = new DiagnosticDescriptor(
        "ACRUX011",
        "Invalid preview value",
        "[PreviewWith] on '{0}.{1}': value '{2}' {3}",
        "Acrux.Generator",
        DiagnosticSeverity.Error,
        true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var input = context.CompilationProvider.Combine(DesignSources.GetProvider(context));
        context.RegisterSourceOutput("preview-clones", input, static (output, pair) =>
        {
            Compilation compilation = pair.Left;
            DesignSources design = pair.Right;
            foreach (PreviewClones.Clone clone in PreviewClones.Plan(compilation, design).Values)
                output.AddSource(design.HintName(Hint(clone.Original) + ".Preview.g.cs", true), Build(clone, output));
        });
    }

    static string Hint(INamedTypeSymbol type)
    {
        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty).Replace('.', '_');
    }

    static string Build(PreviewClones.Clone clone, SourceProductionContext output)
    {
        var statics = new StringBuilder();
        var fields = new StringBuilder();
        var properties = new StringBuilder();
        var assignments = new StringBuilder();
        foreach (PreviewClones.Member member in clone.Members)
        {
            string type = member.CloneTypeName;
            string field = "_" + char.ToLowerInvariant(member.Name[0]) + member.Name.Substring(1);
            fields.Append("        ").Append(type).Append(' ').Append(field).AppendLine(";");
            properties.Append("        public ").Append(type).Append(' ').Append(member.Name).Append(" { get { return ").Append(field)
                .Append("; } set { RaiseAndSetIfChanged(ref ").Append(field).Append(", value, nameof(").Append(member.Name).AppendLine(")); } }");
            string value = Value(clone, member, statics, output);
            if (value != null)
                assignments.Append("            ").Append(field).Append(" = ").Append(value).AppendLine(";");
            if (value != null && member.Kind != PreviewClones.MemberKind.Value)
            {
                NestedOverrides(clone, member, field, statics, assignments, output);
                LinkBack(clone, member, field, assignments);
            }
        }
        foreach (string path in clone.Overrides.Keys)
        {
            string head = path.Split('.')[0];
            if (!clone.Members.Any(m => m.Name == head) || path.Count(c => c == '.') > 1)
                ReportPath(output, clone, path, path.Count(c => c == '.') > 1
                    ? "goes deeper than one nested member"
                    : "names no bindable member of " + clone.Original.Name);
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.Append("// The IDE preview's clone of ").Append(clone.Original.ToDisplayString())
            .AppendLine(", from its [PreviewWith] values. Design build only: MDK does not pack design sources.");
        if (clone.Namespace.Length > 0)
            builder.Append("namespace ").AppendLine(clone.Namespace).AppendLine("{");
        builder.Append("    /// <summary>Preview design data of <see cref=\"").Append(clone.Original.Name)
            .AppendLine("\"/>: its static properties are the values the preview shows (the Rider plugin edits them).</summary>");
        builder.Append("    internal static partial class ").AppendLine(clone.PreviewName);
        builder.AppendLine("    {");
        builder.Append(statics);
        builder.Append("        public static ").Append(clone.ModelName).Append(" Default => new ").Append(clone.ModelName).AppendLine("(0);");
        builder.AppendLine();
        builder.AppendLine("        internal static global::Adk.Mvvm.ObservableList<T> ToObservableList<T>(global::System.Collections.Generic.IEnumerable<T> items)");
        builder.AppendLine("        {");
        builder.AppendLine("            var list = new global::Adk.Mvvm.ObservableList<T>();");
        builder.AppendLine("            foreach (T item in items) list.Add(item);");
        builder.AppendLine("            return list;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.Append("    /// <summary>The preview's clone of <see cref=\"").Append(clone.Original.Name)
            .AppendLine("\"/>: the same bindable properties, filled from its preview design data.</summary>");
        builder.Append("    internal sealed partial class ").Append(clone.ModelName).AppendLine(" : global::Adk.Mvvm.ObservableObject");
        builder.AppendLine("    {");
        builder.Append(fields);
        builder.AppendLine();
        builder.Append("        /// <param name=\"index\">The clone's position in a preview list (values given per item cycle over it).</param>")
            .AppendLine();
        builder.Append("        public ").Append(clone.ModelName).AppendLine("(int index)");
        builder.AppendLine("        {");
        builder.Append(assignments);
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append(properties);
        builder.AppendLine("    }");
        if (clone.Namespace.Length > 0)
            builder.AppendLine("}");
        return builder.ToString();
    }

    // The member's value in the clone: a design property (one value, or none: editable either way), the item's own
    // value from several, a nested clone, or a list of clones.
    static string Value(PreviewClones.Clone clone, PreviewClones.Member member, StringBuilder statics, SourceProductionContext output)
    {
        TypedConstant[] values = member.Values.Items;
        switch (member.Kind)
        {
            case PreviewClones.MemberKind.Model:
                // A view model leading back to this one (an owner link) stays null: cloning it would never end.
                return PreviewClones.IsBackLink(clone, member) ? null : "new " + member.Target.ModelFullName + "(index)";
            case PreviewClones.MemberKind.ModelList:
            {
                int count = 0;
                if (PreviewClones.IsBackLink(clone, member))
                    return "new " + member.CloneTypeName + "()";
                if (values.Length > 0 && !(values[0].Value is int))
                    Report(output, clone, member, values[0], "expects an item count");
                else if (values.Length > 0)
                    count = (int)values[0].Value;
                var items = Enumerable.Range(0, count).Select(i => "new " + member.Target.ModelFullName + "(" + i + ")");
                return "new " + member.CloneTypeName + " { " + string.Join(", ", items) + " }";
            }
        }

        // Commands and handlers have no design value: the clone stubs them, so what binds them (ContextRequested, a
        // button's Command) reacts in the preview and reports the call.
        string stub = InvocationStub(clone, member);
        if (stub != null)
            return stub;

        string type = member.CloneTypeName;
        INamedTypeSymbol element = PreviewClones.ElementType(member.Type);
        if (element != null)
            return ListValue(clone, member, element, values, output);

        if (values.Length > 1)
        {
            var expressions = new List<string>();
            foreach (TypedConstant value in values)
            {
                string error;
                string expression = PreviewClones.Expression(value, member.Type, out error);
                if (expression == null)
                {
                    Report(output, clone, member, value, error);
                    return null;
                }
                expressions.Add(expression);
            }
            statics.Append("        internal static readonly ").Append(type).Append("[] ").Append(member.Name).Append("Values = { ")
                .Append(string.Join(", ", expressions)).AppendLine(" };");
            return clone.PreviewName + "." + member.Name + "Values[index % " + expressions.Count + "]";
        }

        string initial = null;
        if (values.Length == 1)
        {
            string error;
            initial = PreviewClones.Expression(values[0], member.Type, out error);
            if (initial == null)
            {
                Report(output, clone, member, values[0], error);
                return null;
            }
        }
        else if (member.Type.SpecialType == SpecialType.System_String)
            initial = "string.Empty";
        if (!IsSettableStatic(member.Type))
            return initial;
        statics.Append("        public static ").Append(type).Append(' ').Append(member.Name).Append(" { get; set; }");
        if (initial != null)
            statics.Append(" = ").Append(initial).Append(';');
        statics.AppendLine();
        return clone.PreviewName + "." + member.Name;
    }

    // Class-level "Member.Item" values: set on the nested clone, or on every item of the list (item i takes value i).
    static void NestedOverrides(PreviewClones.Clone clone, PreviewClones.Member member, string field, StringBuilder statics,
        StringBuilder assignments, SourceProductionContext output)
    {
        string prefix = member.Name + ".";
        foreach (KeyValuePair<string, PreviewClones.ImmutableValues> entry in clone.Overrides)
        {
            if (!entry.Key.StartsWith(prefix, System.StringComparison.Ordinal) || entry.Key.IndexOf('.', prefix.Length) >= 0)
                continue;
            string name = entry.Key.Substring(prefix.Length);
            PreviewClones.Member target = member.Target.Members.FirstOrDefault(m => m.Name == name);
            if (target != null && target.Kind == PreviewClones.MemberKind.ModelList)
            {
                NestedCount(clone, member, field, target, entry.Value.Items, statics, assignments, output);
                continue;
            }
            if (target == null || target.Kind != PreviewClones.MemberKind.Value)
            {
                ReportPath(output, clone, entry.Key, "names no plain member or list of " + member.Target.Original.Name);
                continue;
            }
            var expressions = new List<string>();
            foreach (TypedConstant value in entry.Value.Items)
            {
                string error;
                string expression = PreviewClones.Expression(value, target.Type, out error);
                if (expression == null)
                {
                    Report(output, clone, target, value, error);
                    return;
                }
                expressions.Add(expression);
            }
            if (expressions.Count == 0)
                continue;
            string staticName = member.Name + "_" + name;
            string type = target.CloneTypeName;
            string pick;
            if (expressions.Count == 1 && IsSettableStatic(target.Type))
            {
                statics.Append("        public static ").Append(type).Append(' ').Append(staticName).Append(" { get; set; } = ")
                    .Append(expressions[0]).AppendLine(";");
                pick = clone.PreviewName + "." + staticName;
            }
            else
            {
                statics.Append("        internal static readonly ").Append(type).Append("[] ").Append(staticName).Append("Values = { ")
                    .Append(string.Join(", ", expressions)).AppendLine(" };");
                pick = clone.PreviewName + "." + staticName + "Values[{0} % " + expressions.Count + "]";
            }
            if (member.Kind == PreviewClones.MemberKind.ModelList)
                assignments.Append("            for (int __i = 0; __i < ").Append(field).Append(".Count; __i++) ").Append(field)
                    .Append("[__i].").Append(name).Append(" = ").Append(string.Format(pick, "__i")).AppendLine(";");
            else
                assignments.Append("            if (").Append(field).Append(" != null) ").Append(field).Append('.').Append(name)
                    .Append(" = ").Append(string.Format(pick, "index")).AppendLine(";");
        }
    }

    // "Member.List" item counts: the nested clone's (or each item's) list gets that many clones (item i takes count i).
    static void NestedCount(PreviewClones.Clone clone, PreviewClones.Member member, string field, PreviewClones.Member target,
        TypedConstant[] values, StringBuilder statics, StringBuilder assignments, SourceProductionContext output)
    {
        var counts = new List<int>();
        foreach (TypedConstant value in values)
        {
            if (!(value.Value is int count))
            {
                Report(output, clone, target, value, "expects an item count");
                return;
            }
            counts.Add(count);
        }
        if (counts.Count == 0 || PreviewClones.IsBackLink(member.Target, target))
            return;
        string staticName = member.Name + "_" + target.Name + "Counts";
        statics.Append("        internal static readonly int[] ").Append(staticName).Append(" = { ").Append(string.Join(", ", counts)).AppendLine(" };");
        string make = "global::System.Linq.Enumerable.Select(global::System.Linq.Enumerable.Range(0, " + clone.PreviewName + "." +
                      staticName + "[{0} % " + counts.Count + "]), __n => new " + target.Target.ModelFullName + "(__n))";
        string list = target.CloneTypeName.StartsWith("global::Adk.Mvvm.ObservableList<", System.StringComparison.Ordinal)
            ? clone.PreviewName + ".ToObservableList(" + make + ")"
            : "new " + target.CloneTypeName + "(" + make + ")";
        if (member.Kind == PreviewClones.MemberKind.ModelList)
            assignments.Append("            for (int __i = 0; __i < ").Append(field).Append(".Count; __i++) ").Append(field)
                .Append("[__i].").Append(target.Name).Append(" = ").Append(string.Format(list, "__i")).AppendLine(";");
        else
            assignments.Append("            if (").Append(field).Append(" != null) ").Append(field).Append('.').Append(target.Name)
                .Append(" = ").Append(string.Format(list, "index")).AppendLine(";");
    }

    // An item's link up to its owner (left empty when the item is created) is this clone, as in the original's graph.
    static void LinkBack(PreviewClones.Clone clone, PreviewClones.Member member, string field, StringBuilder assignments)
    {
        foreach (PreviewClones.Member link in member.Target.Members)
        {
            if (link.Kind != PreviewClones.MemberKind.Model || link.Target != clone || !PreviewClones.IsBackLink(member.Target, link))
                continue;
            if (member.Kind == PreviewClones.MemberKind.ModelList)
                assignments.Append("            foreach (var __item in ").Append(field).Append(") __item.").Append(link.Name).AppendLine(" = this;");
            else
                assignments.Append("            if (").Append(field).Append(" != null) ").Append(field).Append('.').Append(link.Name).AppendLine(" = this;");
        }
    }

    static void ReportPath(SourceProductionContext output, PreviewClones.Clone clone, string path, string error)
    {
        output.ReportDiagnostic(Diagnostic.Create(InvalidValue, clone.Original.Locations.FirstOrDefault() ?? Location.None,
            clone.Original.Name, path, path, error));
    }

    // A collection of plain values: its preview values are the items.
    static string ListValue(PreviewClones.Clone clone, PreviewClones.Member member, INamedTypeSymbol element,
        TypedConstant[] values, SourceProductionContext output)
    {
        var items = new List<string>();
        foreach (TypedConstant value in values)
        {
            string error;
            string expression = PreviewClones.Expression(value, element, out error);
            if (expression == null)
            {
                Report(output, clone, member, value, error);
                return null;
            }
            items.Add(expression);
        }
        string elementName = element.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string list = "new global::System.Collections.Generic.List<" + elementName + "> { " + string.Join(", ", items) + " }";
        if (member.Type is IArrayTypeSymbol)
            return "new " + elementName + "[] { " + string.Join(", ", items) + " }";
        string original = member.Type.OriginalDefinition.ToDisplayString();
        switch (original)
        {
            case "System.Collections.Generic.List<T>":
            case "System.Collections.Generic.IList<T>":
            case "System.Collections.Generic.ICollection<T>":
            case "System.Collections.Generic.IEnumerable<T>":
            case "System.Collections.Generic.IReadOnlyList<T>":
            case "System.Collections.Generic.IReadOnlyCollection<T>":
                return list;
            case "Adk.Mvvm.ObservableList<T>":
            {
                var builder = new StringBuilder("new global::Adk.Mvvm.ObservableList<" + elementName + ">()");
                return items.Count == 0 ? builder.ToString() : builder.Append(" { ").Append(string.Join(", ", items)).Append(" }").ToString();
            }
        }
        if (values.Length > 0)
            Report(output, clone, member, values[0], "has no preview value form for " + member.Type.Name);
        return null;
    }

    // The category the preview host forwards to its log (Trace, so the clone needs nothing of the host).
    internal const string PreviewTraceCategory = "Acrux preview";

    // An Acrux ICommand, or a delegate returning nothing (Action, Action<T>, custom handlers), as a stub that writes
    // "Owner.Member(arguments)" to the preview's trace. Null for anything else: a Func may be polled every frame and
    // stays unset; so does a delegate with ref or out parameters, which a lambda would have to assign.
    static string InvocationStub(PreviewClones.Clone clone, PreviewClones.Member member)
    {
        ITypeSymbol type = member.Type;
        string label = clone.Original.Name + "." + member.Name;
        string category = SymbolDisplay.FormatLiteral(PreviewTraceCategory, true);
        string full = type.OriginalDefinition.ToDisplayString();
        if (full == "Acrux.Core.Input.ICommand" || full == "Acrux.Core.Input.DelegateCommand")
            return "new global::Acrux.Core.Input.DelegateCommand(__parameter => global::System.Diagnostics.Trace.WriteLine(" +
                   SymbolDisplay.FormatLiteral(label + "(", true) + " + global::System.Convert.ToString(__parameter, " +
                   "global::System.Globalization.CultureInfo.InvariantCulture) + \")\", " + category + "))";

        var named = type as INamedTypeSymbol;
        IMethodSymbol invoke = named == null || named.TypeKind != TypeKind.Delegate ? null : named.DelegateInvokeMethod;
        if (invoke == null || !invoke.ReturnsVoid || invoke.Parameters.Any(p => p.RefKind != RefKind.None))
            return null;
        var parameters = invoke.Parameters.Select((p, i) => "__p" + i).ToList();
        string arguments = parameters.Count == 0
            ? SymbolDisplay.FormatLiteral(label + "()", true)
            : SymbolDisplay.FormatLiteral(label + "(", true) + " + " + string.Join(" + \", \" + ", parameters.Select(p =>
                  "global::System.Convert.ToString(" + p + ", global::System.Globalization.CultureInfo.InvariantCulture)")) +
              " + \")\"";
        return "new " + type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "((" + string.Join(", ", parameters) +
               ") => global::System.Diagnostics.Trace.WriteLine(" + arguments + ", " + category + "))";
    }

    // Design properties the Rider plugin edits (string, bool, numbers, enums, Color), and vectors.
    static bool IsSettableStatic(ITypeSymbol type)
    {
        var named = type as INamedTypeSymbol;
        if (named != null && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            type = named.TypeArguments[0];
        if (type.TypeKind == TypeKind.Enum)
            return true;
        switch (type.SpecialType)
        {
            case SpecialType.System_String: case SpecialType.System_Boolean: case SpecialType.System_Int32:
            case SpecialType.System_Int64: case SpecialType.System_Single: case SpecialType.System_Double:
                return true;
        }
        string full = type.ToDisplayString();
        return full == "VRageMath.Color" || full == "VRageMath.Vector2" || full == "VRageMath.Vector3" || full == "VRageMath.Vector4";
    }

    static void Report(SourceProductionContext output, PreviewClones.Clone clone, PreviewClones.Member member, TypedConstant value, string error)
    {
        output.ReportDiagnostic(Diagnostic.Create(InvalidValue, MemberLocation(clone, member), clone.Original.Name, member.Name,
            value.IsNull ? "null" : System.Convert.ToString(value.Value, System.Globalization.CultureInfo.InvariantCulture), error));
    }

    static Location MemberLocation(PreviewClones.Clone clone, PreviewClones.Member member)
    {
        ISymbol symbol = clone.Original.GetMembers(member.Name).FirstOrDefault() ??
                         clone.Original.GetMembers().OfType<IFieldSymbol>()
                             .FirstOrDefault(f => ObservablePropertyConventions.PropertyName(f.Name) == member.Name);
        return symbol?.Locations.FirstOrDefault() ?? Location.None;
    }
}
