using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Adk.Analyzer;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Acrux.Generator;

/// <summary>
/// Implements Acrux.Markup.GeneratedTypeCatalog so runtime styles and templates can create
/// controls compiled with Acrux. Acrux controls expose only their whitelisted base members
/// (see BaseMembers); app controls additionally expose the properties they declare.
/// </summary>
[Generator]
public sealed class AcruxRuntimeTypeGenerator : IIncrementalGenerator
{
    const string CatalogTypeName = "Acrux.Markup.GeneratedTypeCatalog";
    const string ControlTypeName = "Acrux.Core.Control";

    static readonly HashSet<string> CommonPropertyOwners = new HashSet<string>(StringComparer.Ordinal)
    {
        "Acrux.Core.Visual",
        "Acrux.Core.Control",
        "Acrux.Core.FrameworkElement",
        "Acrux.Core.VisualElement"
    };

    static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.CompilationProvider.Combine(DesignSources.GetProvider(context))
            .Select(static (input, _) => Generate(input.Left, input.Right));
        context.RegisterSourceOutput("gui", source, static (output, text) =>
        {
            if (!string.IsNullOrEmpty(text))
                output.AddSource("Acrux.GeneratedTypeCatalog.g.cs", text);
        });
    }

    static string Generate(Compilation compilation, DesignSources design)
    {
        INamedTypeSymbol catalog = compilation.GetTypeByMetadataName(CatalogTypeName);
        INamedTypeSymbol control = compilation.GetTypeByMetadataName(ControlTypeName);
        if (control != null && compilation.GetTypeByMetadataName(ToolkitClientTypeName) != null)
            return GenerateToolkitClient(compilation, control, design);
        if (catalog == null || control == null ||
            !SymbolEqualityComparer.Default.Equals(catalog.ContainingAssembly, compilation.Assembly))
            return null;

        var types = new List<INamedTypeSymbol>();
        CollectTypes(compilation.Assembly.GlobalNamespace, control, compilation, design, types);
        types.Sort((left, right) => string.CompareOrdinal(MetadataName(left), MetadataName(right)));

        var shortNameCounts = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (INamedTypeSymbol type in types.Where(type => BaseMemberWhitelist.IsAcruxType(type) && BaseMemberWhitelist.IsBaseType(type)))
        {
            int count;
            shortNameCounts.TryGetValue(type.Name, out count);
            shortNameCounts[type.Name] = count + 1;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("namespace Acrux.Markup");
        builder.AppendLine("{");
        builder.AppendLine("    internal static partial class GeneratedTypeCatalog");
        builder.AppendLine("    {");
        builder.AppendLine("        static partial void RegisterStyleTypes(global::Acrux.Styling.StylePropertyRegistry registry)");
        builder.AppendLine("        {");
        foreach (INamedTypeSymbol type in types)
        {
            string typeName = type.ToDisplayString(TypeFormat);
            builder.Append("            registry.RegisterType<").Append(typeName).Append(">(")
                .Append(Literal(MetadataName(type))).AppendLine(");");
            if (HasUniqueShortName(type, shortNameCounts))
                builder.Append("            registry.TryRegisterType<").Append(typeName).Append(">(")
                    .Append(Literal(type.Name)).AppendLine(");");
        }
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        static partial void TouchStyledProperties()");
        builder.AppendLine("        {");
        foreach (INamedTypeSymbol type in types)
            foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
                if (field.IsStatic && IsStyledProperty(field.Type) &&
                    !field.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.ObsoleteAttribute") &&
                    compilation.IsSymbolAccessibleWithin(field, compilation.Assembly))
                    builder.Append("            Touch(").Append(type.ToDisplayString(TypeFormat)).Append('.')
                        .Append(EscapeIdentifier(field.Name)).AppendLine(");");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        static partial void RegisterTemplateTypes(global::Acrux.Markup.TypeRegistry registry)");
        builder.AppendLine("        {");
        var creatable = types.Where(type => CanCreate(type, compilation) &&
                                            (!BaseMemberWhitelist.IsAcruxType(type) ||
                                             BaseMemberWhitelist.IsBaseType(type) ||
                                             BaseMemberWhitelist.IsExtension(type))).ToList();
        for (int i = 0; i < creatable.Count; i++)
            builder.Append("            RegisterTemplateType").Append(i).AppendLine("(registry);");
        builder.AppendLine("        }");

        for (int i = 0; i < creatable.Count; i++)
        {
            INamedTypeSymbol type = creatable[i];
            string typeName = type.ToDisplayString(TypeFormat);
            builder.AppendLine();
            builder.Append("        static void RegisterTemplateType").Append(i)
                .AppendLine("(global::Acrux.Markup.TypeRegistry registry)");
            builder.AppendLine("        {");
            string name = Literal(MetadataName(type));
            builder.Append("            registry.Register<").Append(typeName).Append(">(")
                .Append(name).Append(", () => new ").Append(typeName).AppendLine("());");
            foreach (IPropertySymbol property in SettableProperties(type, compilation))
            {
                builder.Append("            registry.RegisterProperty<").Append(typeName).Append(", ")
                    .Append(property.Type.ToDisplayString(TypeFormat)).Append(">(")
                    .Append(name).Append(", ").Append(Literal(property.Name))
                    .Append(", (control, value) => control.").Append(EscapeIdentifier(property.Name))
                    .AppendLine(" = value);");
            }
            if (HasUniqueShortName(type, shortNameCounts))
                builder.Append("            registry.RegisterAlias(").Append(Literal(type.Name)).Append(", ")
                    .Append(name).AppendLine(");");
            builder.AppendLine("        }");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    const string ToolkitClientTypeName = "Acrux.Toolkit.AcruxUiToolkitClient";

    // An Acrux UI Toolkit client compiles thin wrappers instead of Acrux. Its own control types are announced to the
    // toolkit so toolkit-side styles and templates can select and create them.
    static string GenerateToolkitClient(Compilation compilation, INamedTypeSymbol control, DesignSources design)
    {
        var types = new List<INamedTypeSymbol>();
        CollectTypes(compilation.Assembly.GlobalNamespace, control, compilation, design, types);
        types.RemoveAll(type => BaseMemberWhitelist.IsAcruxType(type) || !type.Locations.Any(location => location.IsInSource));
        types.Sort((left, right) => string.CompareOrdinal(MetadataName(left), MetadataName(right)));
        var shortNames = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (INamedTypeSymbol type in types)
        {
            int count;
            shortNames.TryGetValue(type.Name, out count);
            shortNames[type.Name] = count + 1;
        }

        const string ui = "global::Acrux.Toolkit.Ui";
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("namespace Acrux.Toolkit");
        builder.AppendLine("{");
        builder.AppendLine("    public static partial class Ui");
        builder.AppendLine("    {");
        builder.AppendLine("        static partial void RegisterClientCatalog()");
        builder.AppendLine("        {");
        foreach (INamedTypeSymbol type in types)
        {
            string typeName = type.ToDisplayString(TypeFormat);
            builder.Append("            ").Append(ui).Append(".RegisterStyleType<").Append(typeName).Append(">(")
                .Append(Literal(MetadataName(type))).AppendLine(");");
            int count;
            if (shortNames.TryGetValue(type.Name, out count) && count == 1)
                builder.Append("            ").Append(ui).Append(".RegisterStyleType<").Append(typeName).Append(">(")
                    .Append(Literal(type.Name)).AppendLine(");");
        }
        foreach (INamedTypeSymbol type in types)
            foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
                if (field.IsStatic && IsStyledProperty(field.Type) &&
                    compilation.IsSymbolAccessibleWithin(field, compilation.Assembly))
                    builder.Append("            global::Acrux.Toolkit.Ui.Touch(").Append(type.ToDisplayString(TypeFormat)).Append('.')
                        .Append(EscapeIdentifier(field.Name)).AppendLine(");");
        foreach (INamedTypeSymbol type in types.Where(type => CanCreate(type, compilation)))
        {
            string typeName = type.ToDisplayString(TypeFormat);
            var names = new List<string> { MetadataName(type) };
            int count;
            if (shortNames.TryGetValue(type.Name, out count) && count == 1)
                names.Add(type.Name);
            foreach (string name in names)
            {
                builder.Append("            ").Append(ui).Append(".RegisterTemplateType<").Append(typeName).Append(">(")
                    .Append(Literal(name)).Append(", () => new ").Append(typeName).AppendLine("());");
                foreach (IPropertySymbol property in SettableProperties(type, compilation))
                    builder.Append("            ").Append(ui).Append(".RegisterTemplateProperty<").Append(typeName).Append(", ")
                        .Append(property.Type.ToDisplayString(TypeFormat)).Append(">(")
                        .Append(Literal(name)).Append(", ").Append(Literal(property.Name))
                        .Append(", (control, value) => control.").Append(EscapeIdentifier(property.Name))
                        .AppendLine(" = value);");
            }
        }
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    static void CollectTypes(INamespaceSymbol namespaceSymbol, INamedTypeSymbol control, Compilation compilation,
        DesignSources design, List<INamedTypeSymbol> types)
    {
        foreach (INamespaceSymbol child in namespaceSymbol.GetNamespaceMembers())
            CollectTypes(child, control, compilation, design, types);
        foreach (INamedTypeSymbol type in namespaceSymbol.GetTypeMembers())
        {
            if (type.TypeKind != TypeKind.Class || type.IsStatic || type.IsGenericType ||
                !DerivesFrom(type, control) ||
                !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly) ||
                design.IsDesignOnly(type))
                continue;
            types.Add(type);
        }
    }

    static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (INamedTypeSymbol current = type; current != null; current = current.BaseType)
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
                return true;
        return false;
    }

    static bool CanCreate(INamedTypeSymbol type, Compilation compilation)
    {
        return !type.IsAbstract && type.InstanceConstructors.Any(constructor =>
            constructor.Parameters.Length == 0 &&
            compilation.IsSymbolAccessibleWithin(constructor, compilation.Assembly));
    }

    static IEnumerable<IPropertySymbol> SettableProperties(INamedTypeSymbol type, Compilation compilation)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (INamedTypeSymbol current = type; current != null; current = current.BaseType)
        {
            if (CommonPropertyOwners.Contains(MetadataName(current)))
                break;
            bool acruxMember = BaseMemberWhitelist.IsAcruxType(current);
            INamedTypeSymbol acruxType = BaseMemberWhitelist.NearestAcruxType(type);
            foreach (IPropertySymbol property in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (!seen.Add(property.Name))
                    continue;
                if (acruxMember && !BaseMemberWhitelist.IsExtension(current) &&
                    (acruxType == null || !BaseMemberWhitelist.IsBaseType(acruxType) ||
                     !BaseMemberWhitelist.IsAllowedMember(type, property.Name)))
                    continue;
                IMethodSymbol setter = FindSetter(property);
                if (property.IsStatic || property.IsIndexer || property.ReturnsByRef ||
                    property.ReturnsByRefReadonly || setter == null || setter.IsInitOnly ||
                    !compilation.IsSymbolAccessibleWithin(setter, compilation.Assembly) ||
                    !IsAccessible(property.Type, compilation))
                    continue;
                yield return property;
            }
        }
    }

    static bool IsStyledProperty(ITypeSymbol type)
    {
        var named = type as INamedTypeSymbol;
        return named != null && named.Name == "StyledProperty" &&
               named.ContainingNamespace.ToDisplayString() == "Acrux.Core.PropertySystem";
    }

    static IMethodSymbol FindSetter(IPropertySymbol property)
    {
        for (IPropertySymbol current = property; current != null; current = current.OverriddenProperty)
            if (current.SetMethod != null)
                return current.SetMethod;
        return null;
    }

    static bool IsAccessible(ITypeSymbol type, Compilation compilation)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return IsAccessible(array.ElementType, compilation);
            case IPointerTypeSymbol _:
            case IFunctionPointerTypeSymbol _:
            case IDynamicTypeSymbol _:
            case ITypeParameterSymbol _:
                return false;
            case INamedTypeSymbol named:
                if (named.IsRefLikeType || !compilation.IsSymbolAccessibleWithin(named, compilation.Assembly))
                    return false;
                return named.TypeArguments.All(argument => IsAccessible(argument, compilation));
            default:
                return false;
        }
    }

    static bool HasUniqueShortName(INamedTypeSymbol type, Dictionary<string, int> shortNameCounts)
    {
        int count;
        return BaseMemberWhitelist.IsAcruxType(type) && shortNameCounts.TryGetValue(type.Name, out count) && count == 1;
    }

    static string MetadataName(INamedTypeSymbol type)
    {
        return type.ContainingNamespace.IsGlobalNamespace
            ? type.Name
            : type.ContainingNamespace.ToDisplayString() + "." + type.Name;
    }

    static string Literal(string value)
    {
        return SymbolDisplay.FormatLiteral(value, true);
    }

    static string EscapeIdentifier(string name)
    {
        return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
    }
}
